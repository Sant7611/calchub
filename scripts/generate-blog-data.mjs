import fs from "node:fs";
import path from "node:path";

const postsDir = path.join(process.cwd(), "src/content/blog");
const outputFile = path.join(
  process.cwd(),
  "src/data/generated-blog-sources.ts",
);

const blogSources = Object.fromEntries(
  fs
    .readdirSync(postsDir)
    .filter((file) => file.endsWith(".mdx"))
    .sort()
    .map((file) => {
      const slug = file.replace(/\.mdx$/, "");
      const raw = fs.readFileSync(path.join(postsDir, file), "utf-8");

      return [slug, raw];
    }),
);

const output = `// AUTO-GENERATED BY scripts/generate-blog-data.mjs\n// Do not edit this file manually.\n\nexport const blogSources: Record<string, string> = ${JSON.stringify(blogSources, null, 2)};\n`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, output, "utf-8");

console.log(`Generated ${Object.keys(blogSources).length} blog sources.`);
